async function streamPlainReply(slug, message) {
  const config = getRunConfig();
  const response = await fetch(`/studio/projects/${encodeURIComponent(slug)}/messages/stream`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      message,
      provider: config.provider,
      model: config.model,
      api_key: config.apiKey,
      language: config.language,
    }),
  });
  if (!response.ok || !response.body) {
    const payload = await response.json().catch(() => null);
    throw new Error(payload?.detail || `HTTP ${response.status}`);
  }

  const bubble = appendChatBubble("assistant", "");
  const streamed = await readStream(response, (text) => {
    if (bubble) bubble.textContent = text;
    if (el.studioChatScroll) el.studioChatScroll.scrollTop = el.studioChatScroll.scrollHeight;
  });
  state.studioSession.messages.push({ role: "assistant", content: streamed });
}

async function readStream(response, onChunk) {
  const reader = response.body.getReader();
  const decoder = new TextDecoder("utf-8");
  let streamed = "";
  while (true) {
    const { value, done } = await reader.read();
    if (done) break;
    streamed += decoder.decode(value, { stream: true });
    onChunk(streamed);
  }
  streamed += decoder.decode();
  return streamed;
}

async function streamAgentReply(slug, message) {
  const config = getRunConfig();
  const response = await fetch(`/studio/projects/${encodeURIComponent(slug)}/agent/stream`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      message,
      provider: config.provider,
      model: config.model,
      api_key: config.apiKey,
      language: config.language,
      mode: state.agentMode,
    }),
  });
  if (!response.ok || !response.body) {
    const payload = await response.json().catch(() => null);
    throw new Error(payload?.detail || `HTTP ${response.status}`);
  }

  const bubble = appendChatBubble("assistant", "");
  let streamed = "";
  const applyText = () => {
    if (bubble) bubble.textContent = streamed;
    if (el.studioChatScroll) el.studioChatScroll.scrollTop = el.studioChatScroll.scrollHeight;
  };

  const reader = response.body.getReader();
  const decoder = new TextDecoder("utf-8");
  let buffer = "";
  while (true) {
    const { value, done } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    const lines = buffer.split("\n");
    buffer = lines.pop() || "";
    for (const line of lines) {
      if (!line.trim()) continue;
      let event;
      try {
        event = JSON.parse(line);
      } catch (_error) {
        continue;
      }
      handleAgentEvent(event, (delta) => {
        streamed += delta;
        applyText();
      });
    }
  }

  state.studioSession.messages.push({ role: "assistant", content: streamed });
  await refreshPendingActions();
}

function handleAgentEvent(event, onText) {
  switch (event.type) {
    case "text_delta":
      onText(event.text || "");
      break;
    case "tool_call": {
      el.studioChatScroll?.insertAdjacentHTML(
        "beforeend",
        studioToolRowHtml(event.tool, event.arguments, event.result),
      );
      if (el.studioChatScroll) el.studioChatScroll.scrollTop = el.studioChatScroll.scrollHeight;
      break;
    }
    case "notice":
      showToast(`${t("studio_agent_notice")}: ${event.message}`, false);
      break;
    case "error":
      showToast(`${t("studio_error")}: ${event.message}`, true);
      break;
    case "done":
      if (event.actions?.length) {
        state.studioSession.chapterCount = undefined;
        void loadStudioProjects();
        void refreshChapters();
      }
      break;
    default:
      break;
  }
}

